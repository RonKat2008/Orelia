import { expect, it, vi } from 'vitest';
const handlers = vi.hoisted(() => ({ select: vi.fn(), consent: vi.fn(), draft: vi.fn(), approve: vi.fn() }));
vi.mock('../../lib/outreach/server', () => ({ getOutreachHandlers: () => handlers }));
const guards = vi.hoisted(() => ({ guardContact: vi.fn(), requireCaseOwner: vi.fn(), rejectCrossOrigin: vi.fn() }));
vi.mock('../../lib/auth/ownership', () => ({ guardContact: guards.guardContact, requireCaseOwner: guards.requireCaseOwner }));
vi.mock('../../lib/auth/origin', () => ({ rejectCrossOrigin: guards.rejectCrossOrigin }));
import { POST as select } from '../../app/api/outreach/select/route';
import { PUT as consent } from '../../app/api/contacts/[id]/consent/route';
import { POST as draft } from '../../app/api/contacts/[id]/drafts/route';
import { POST as approve } from '../../app/api/contacts/[id]/approve/route';
it('App Router routes delegate the request and awaited contact ID to validated handlers', async () => {
  guards.guardContact.mockResolvedValue(null);
  guards.rejectCrossOrigin.mockReturnValue(null);
  guards.requireCaseOwner.mockResolvedValue({ ok: true, sessionId: 's' });
  const body = JSON.stringify({ caseId: 'case-id' });
  const request = new Request('http://localhost', { method: 'POST', body });
  const context = { params: Promise.resolve({ id: 'contact-id' }) };
  for (const fn of Object.values(handlers)) fn.mockResolvedValue(Response.json({ ok: true }));
  await select(request);
  expect(guards.rejectCrossOrigin).toHaveBeenCalledWith(request);
  expect(guards.requireCaseOwner).toHaveBeenCalledWith(request, 'case-id');
  expect(handlers.select).toHaveBeenCalledTimes(1);
  // The route reads the body to find the case, then replays it to the handler in a fresh request.
  expect(await (handlers.select.mock.calls[0]![0] as Request).text()).toBe(body);
  await consent(request, context);
  expect(guards.guardContact).toHaveBeenLastCalledWith(request, 'contact-id');
  expect(handlers.consent).toHaveBeenCalledWith(request, 'contact-id');
  await draft(request, context);
  expect(guards.guardContact).toHaveBeenCalledTimes(2);
  expect(handlers.draft).toHaveBeenCalledWith(request, 'contact-id');
  await approve(request, context);
  expect(guards.guardContact).toHaveBeenCalledTimes(3);
  expect(handlers.approve).toHaveBeenCalledWith(request, 'contact-id');
});
