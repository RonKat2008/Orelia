export function timezoneForHomeState(homeState: string | null | undefined): string {
  const code = (homeState ?? '').trim().toUpperCase();
  return STATE_TZ[code] ?? 'America/New_York';
}

export function localParts(now: Date, timeZone: string): { hour: number; date: string } {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone,
    hour: '2-digit',
    hourCycle: 'h23',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(now);
  const get = (type: string) => parts.find((p) => p.type === type)?.value ?? '';
  const hour = Number(get('hour'));
  return { hour, date: `${get('year')}-${get('month')}-${get('day')}` };
}

/** 9:00pm through 7:59am in the patient's home-state timezone. */
export function isQuietHours(now: Date, homeState: string | null | undefined): boolean {
  const { hour } = localParts(now, timezoneForHomeState(homeState));
  return hour >= 21 || hour < 8;
}
